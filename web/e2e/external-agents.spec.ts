import { test, expect, type WebSocketRoute } from '@playwright/test';

test('external settings, selector and native activity survive reload', async ({ page }) => {
  let socket: WebSocketRoute | undefined;
  await page.routeWebSocket('**/api/v1/events', ws => { socket = ws; ws.connectToServer(); });
  await page.goto('/');
  await expect(page.locator('#new-chat')).toBeVisible();
  const before = await (await page.request.get('/api/v1/state')).json();
  for (const endpoint of before.endpoints) if (endpoint.name === 'Browser CLI fixture') await page.request.delete(`/api/v1/endpoints/${endpoint.id}`);
  const created = page.waitForResponse(r => r.url().endsWith('/api/v1/chats') && r.request().method() === 'POST');
  await page.locator('#new-chat').click();
  const chat = await (await created).json();
  await page.locator('#settings-button').click();
  await page.getByRole('button', { name: 'External Agents', exact: true }).click();
  await expect(page.locator('.settings-content')).toContainText('Echo folder restrictions and plugin permissions do not apply.');
  await page.getByRole('button', { name: '＋ Add external agent', exact: true }).click();
  const form = page.locator('.external-agent-form');
  await form.getByLabel('Name', { exact: true }).fill('Browser CLI fixture');
  await form.getByLabel('CLI', { exact: true }).selectOption('claude-code-cli');
  await expect(form.locator('[name=url], [name=key], [name=temperature]')).toHaveCount(0);
  await form.getByRole('button', { name: 'Save connection' }).click();
  await expect(page.locator('.settings-content')).toContainText('Browser CLI fixture');
  await page.keyboard.press('Escape');
  await page.locator('[data-generation-settings] > summary').click();
  const selector = page.getByRole('dialog', { name: 'Model Settings', exact: true });
  await expect(selector).toContainText('External agent · Full access.');
  await expect(selector.getByRole('slider', { name: 'Temperature' })).toBeHidden();
  await expect(selector.getByRole('slider', { name: 'Thinking' })).toBeVisible();
  await expect(selector.getByLabel('Model identifier', { exact: true })).toHaveAttribute('placeholder', 'CLI default');
  const reset = page.waitForResponse(r => r.url().endsWith('/external-agents/reset'));
  await selector.getByRole('button', { name: 'Reset external sessions' }).click();
  expect((await reset).ok()).toBe(true);

  const base = { chatId: chat.id, botId: 'echo', runId: 'external-browser-run', createdAt: new Date().toISOString() };
  const activity = { ...base, id: 'external-browser-tool', role: 'activity', author: 'Echo · Bash', content: '{"command":"echo browser fixture"}', status: 'running' };
  const text = { ...base, id: 'external-browser-text', role: 'activity', author: 'Echo · Response', content: 'Native partial response', status: 'running' };
  const emit = (payload: unknown) => socket!.send(JSON.stringify({ type: 'message', chatId: chat.id, payload }));
  emit(activity); emit(text);
  await expect(page.locator('.message.activity pre').last()).toBeVisible();
  await expect(page.locator('.message.activity').last()).toContainText('Native partial response');
  text.content += ' updated'; emit(text);
  await expect(page.locator('.message.activity').last()).toContainText('Native partial response updated');
  activity.content += '\nResult: browser fixture'; activity.status = 'completed'; text.status = 'completed';
  emit(activity); emit(text);
  const final = { ...base, id: 'external-browser-final', role: 'assistant', author: 'Echo', content: 'Native final answer', status: 'completed' };
  emit(final);
  await expect(page.locator('.message.assistant')).toContainText('Native final answer');
  await page.getByText('Show work', { exact: true }).click();
  await page.locator('.message.activity').first().locator('summary').click();
  await expect(page.locator('.message.activity').first().locator('pre')).toContainText('Result: browser fixture');
  await page.route(`**/api/v1/chats/${chat.id}/snapshot`, async route => {
    const data = await (await route.fetch()).json();
    await route.fulfill({ json: { ...data, messages: [activity, text, final] } });
  });
  await page.reload();
  await expect(page.locator('.message.assistant')).toContainText('Native final answer');
  await page.getByText('Show work', { exact: true }).click();
  await expect(page.locator('.message.activity')).toHaveCount(2);
  const state = await (await page.request.get('/api/v1/state')).json();
  const endpoint = state.endpoints.find((e: { name: string }) => e.name === 'Browser CLI fixture');
  expect(endpoint.kind).toBe('claude-code-cli');
  await page.request.delete(`/api/v1/endpoints/${endpoint.id}`);
  await page.request.delete(`/api/v1/chats/${chat.id}`);
});
