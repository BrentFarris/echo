import { test, expect } from '@playwright/test';
import { mkdir, writeFile, readFile } from 'node:fs/promises';
import { execFileSync } from 'node:child_process';
import path from 'node:path';

 test('source control selection, bulk actions, shared editable split diff and recovery', async ({page})=>{
  test.setTimeout(120_000);
  const errors:string[]=[]; page.on('pageerror',e=>errors.push(e.message));
  const root=path.resolve('../.test-data/scm-fixtures',String(Date.now()));
  await mkdir(root,{recursive:true});
  const git=(...args:string[])=>execFileSync('git',args,{cwd:root,env:{...process.env,GIT_CONFIG_NOSYSTEM:'1',GIT_CONFIG_GLOBAL:process.platform==='win32'?'NUL':'/dev/null',GIT_AUTHOR_NAME:'Echo test',GIT_AUTHOR_EMAIL:'test@example.invalid',GIT_COMMITTER_NAME:'Echo test',GIT_COMMITTER_EMAIL:'test@example.invalid'}}).toString();
  git('init');git('config','core.autocrlf','false');
  for(const name of ['alpha.txt','beta.txt','gamma.txt'])await writeFile(path.join(root,name),'original\n'+ 'long line '.repeat(70)+'\n');
  git('add','.');git('commit','-m','initial');
  for(const name of ['alpha.txt','beta.txt','gamma.txt'])await writeFile(path.join(root,name),'changed\nshort\n');
  await page.goto('/');await page.request.post('/api/v1/session',{data:{}});
  const state = await (await page.request.get('/api/v1/state')).json();
  const created = await page.request.post('/api/v1/bots',{data:{...state.bots.find((bot:any)=>bot.handle==='echoapp'),handle:'echoapp',name:'SCM Echo App',roots:[root]}});
  expect(created.ok()).toBeTruthy();
  await page.request.patch('/api/v1/plugins/monaco-editor',{data:{enabled:true,config:{}}});
  await page.reload();await page.locator('#apps-button').click();
  await page.locator('[data-app-id="monaco-editor"]').getByRole('button',{name:'Open Monaco Editor',exact:true}).click();
  const botOption = await page.getByLabel('Editor bot').locator('option').filter({hasText:'SCM Echo App'}).getAttribute('value');
  await page.getByLabel('Editor bot').selectOption(botOption!);
  const editor=page.locator('.editor-bot-session:not([hidden])');
  await expect(editor.locator('.code-app-shell')).toHaveAttribute('aria-busy','false');
  let releaseDiscovery!: () => void;
  const discoveryGate = new Promise<void>(resolve => { releaseDiscovery = resolve; });
  let discoveryRequests = 0;
  await page.route('**/source-control/repositories', async route => {
    discoveryRequests++;
    await discoveryGate;
    await route.continue();
  });
  await editor.getByRole('button',{name:'Source Control',exact:true}).click();
  await expect(editor.getByText('Discovering repositories…')).toBeVisible();
  await expect(editor.getByRole('button',{name:'Refresh Source Control',exact:true})).toBeVisible();
  await expect.poll(() => discoveryRequests).toBe(1);
  await editor.getByRole('button',{name:'Source Control',exact:true}).click();
  expect(discoveryRequests).toBe(1);
  releaseDiscovery();
  const working=editor.locator('[data-git-group-id="unstaged"]');
  const row=(name:string)=>working.locator('[role=option]').filter({hasText:name});
  await expect(row('alpha.txt')).toBeVisible({timeout:30_000});
  await row('alpha.txt').click(); await row('gamma.txt').click({modifiers:['Shift']});
  await expect(working.locator('[aria-selected=true]')).toHaveCount(3);
  await row('beta.txt').click({modifiers:['Control']});await expect(working.locator('[aria-selected=true]')).toHaveCount(2);
  await editor.locator('[data-git-commit-message]').fill('retained commit draft');
  await row('alpha.txt').getByRole('button',{name:'Stage Changes',exact:true}).click();
  await expect(editor.locator('[data-git-group-id="staged"] [role=option]')).toHaveCount(2,{timeout:30_000});
  expect(git('diff','--cached','--name-only').trim().split('\n')).toEqual(['alpha.txt','gamma.txt']);
  await expect(editor.locator('[data-git-commit-message]')).toHaveValue('retained commit draft');
  await editor.locator('[data-git-group-id="staged"]').getByRole('button',{name:'Unstage All Changes in Section',exact:true}).click();
  await expect(editor.locator('[data-git-group-id="staged"] [role=option]')).toHaveCount(0);
  await row('beta.txt').getByRole('button',{name:'Stage Changes',exact:true}).click();
  await expect.poll(()=>git('diff','--cached','--name-only').trim()).toBe('beta.txt');
  await editor.locator('[data-git-group-id="staged"]').getByRole('button',{name:'Unstage All Changes in Section',exact:true}).click();
  await expect(row('beta.txt')).toBeVisible();
  await row('beta.txt').dblclick();
  await expect(editor.locator('[data-monaco-diff-host] .monaco-diff-editor')).toBeVisible();
  const scroll=editor.locator('[data-diff-scroll]');
  await expect(scroll).toBeVisible();
  await expect.poll(()=>scroll.evaluate(el=>el.scrollWidth-el.clientWidth)).toBeGreaterThan(500);
  const lines=editor.locator('[data-monaco-diff-host] .view-lines');
  const positions=await lines.evaluateAll(elements=>elements.map(el=>el.getBoundingClientRect().x));
  await scroll.evaluate(el=>{el.scrollLeft=300});
  await expect.poll(()=>lines.evaluateAll(elements=>elements.map(el=>el.getBoundingClientRect().x))).toEqual(positions.map(x=>x-300));
  await scroll.evaluate(el=>{el.scrollLeft=0});
  await expect(editor.getByRole('button',{name:'Revert Change',exact:true}).first()).toBeVisible();
  await editor.getByRole('button',{name:'Revert Change',exact:true}).first().click();
  await expect(editor.getByRole('tab',{name:/beta.txt/}).locator('.code-tab-dirty')).toHaveClass(/is-visible/);
  expect(await readFile(path.join(root,'beta.txt'),'utf8')).toBe('changed\nshort\n');
  await page.keyboard.press('Control+z');
  await page.keyboard.press('Control+s');
  await expect(editor.getByRole('tab',{name:/beta.txt/}).locator('.code-tab-dirty')).not.toHaveClass(/is-visible/);
  await row('beta.txt').getByRole('button',{name:'Open File',exact:true}).click();
  await expect(editor.getByRole('tab',{name:/beta.txt/})).toHaveCount(2);
  await editor.locator('[data-monaco-host] .view-lines').click({position:{x:70,y:10}});
  await page.keyboard.press('Control+End');await page.keyboard.type('shared draft');
  await editor.getByRole('tab',{name:/beta.txt \(Working Tree\)/}).click();
  await expect(editor.locator('[data-monaco-diff-host] .modified .view-lines')).toContainText('shared draft');
  await expect(editor.getByRole('button',{name:'Stage Change',exact:true}).first()).toBeDisabled();
  await page.keyboard.press('Control+s');
  await expect.poll(()=>readFile(path.join(root,'beta.txt'),'utf8')).toContain('shared draft');
  await editor.locator('[data-code-sidebar="explorer"]').click();
  const treeRow=editor.locator('.code-tree-row').filter({hasText:'beta.txt'}).first();
  await treeRow.click();await page.keyboard.press('F2');
  await editor.locator('.code-tree input').fill('renamed.txt');await page.keyboard.press('Enter');
  await expect(editor.getByRole('tab',{name:/renamed.txt/})).toHaveCount(2);
  await editor.getByRole('tab',{name:/renamed.txt \(Working Tree\)/}).click();
  await page.screenshot({path:test.info().outputPath('source-control.png')});
  await page.reload();
  await page.getByLabel('Editor bot').selectOption(botOption!);
  await expect(editor.locator('[data-monaco-diff-host] .monaco-diff-editor')).toBeVisible({timeout:30_000});
  expect(errors).toEqual([]);
 });
